//! Setting up Ghostty to send velmux's prefix-less shortcuts.

use std::path::PathBuf;

use anyhow::{Context, Result};

pub const START: &str = "# --- velmux (generated by `velmux keys --ghostty`) ---";
pub const END: &str = "# --- end velmux ---";

/// Running under Ghostty (as far as this process's environment says).
pub fn detected() -> bool {
    std::env::var("TERM_PROGRAM").is_ok_and(|t| t.eq_ignore_ascii_case("ghostty")) || std::env::var_os("GHOSTTY_RESOURCES_DIR").is_some()
}

/// Ghostty's config file: the XDG one, else (macOS) the app-support one if
/// that's what exists.
pub fn config_path() -> Option<PathBuf> {
    let home = velmux_pool::sys::home()?;
    let xdg = std::env::var_os("XDG_CONFIG_HOME").map(PathBuf::from).unwrap_or_else(|| home.join(".config")).join("ghostty/config");
    let app = home.join("Library/Application Support/com.mitchellh.ghostty/config");
    Some(if !xdg.exists() && app.exists() { app } else { xdg })
}

/// The config already has velmux's block.
pub fn configured() -> bool {
    config_path().and_then(|p| std::fs::read_to_string(p).ok()).is_some_and(|c| c.contains(START))
}

/// `text` with velmux's block (`lines`) put in: replacing the one there (to
/// its end marker, or the end of the file for a block from before markers
/// had ends), else appended.
pub fn with_block(text: &str, lines: &str) -> String {
    let block = format!("{START}\n{}\n{END}\n", lines.trim_end());
    match text.find(START) {
        Some(at) => {
            let rest = &text[at..];
            let after = rest.find(END).map(|e| &rest[e + END.len()..]).unwrap_or("");
            format!("{}{block}{}", &text[..at], after.trim_start_matches('\n'))
        }
        None if text.is_empty() || text.ends_with("\n\n") => format!("{text}{block}"),
        None if text.ends_with('\n') => format!("{text}\n{block}"),
        None => format!("{text}\n\n{block}"),
    }
}

/// Write velmux's keybinds into Ghostty's config; returns its path.
pub fn install(lines: &str) -> Result<PathBuf> {
    let path = config_path().context("HOME is not set")?;
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, with_block(&text, lines)).with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn puts_the_block_in_once() {
        let fresh = with_block("font-size = 15\n", "keybind = a=b");
        assert_eq!(fresh, format!("font-size = 15\n\n{START}\nkeybind = a=b\n{END}\n"));
        // Replaced in place, keeping what's after it.
        let again = with_block(&format!("{fresh}theme = x\n"), "keybind = c=d");
        assert_eq!(again, format!("font-size = 15\n\n{START}\nkeybind = c=d\n{END}\ntheme = x\n"));
        // An old block without an end marker runs to the end of the file.
        let old = with_block(&format!("a = 1\n{START}\n# old\nkeybind = x=y\n"), "keybind = n=m");
        assert_eq!(old, format!("a = 1\n{START}\nkeybind = n=m\n{END}\n"));
    }
}
